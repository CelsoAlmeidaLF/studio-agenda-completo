import asyncio
from playwright.async_api import async_playwright
OUT='capturas/p-'
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width':390,'height':844}, bypass_csp=True)
        pg = await ctx.new_page(); errs=[]
        pg.on('console', lambda m: errs.append(m.text) if m.type=='error' else None)
        pg.on('pageerror', lambda e: errs.append('PAGEERROR '+str(e)))
        await pg.goto('http://localhost:8123/'); await pg.wait_for_selector('form.auth-card')
        ins = pg.locator('form.auth-card input.inp')
        await ins.nth(0).fill('Studio Bella Forma'); await ins.nth(1).fill('Patrícia Souza'); await ins.nth(2).fill('482916'); await ins.nth(3).fill('482916')
        await pg.click('button[type=submit]'); await pg.wait_for_selector('.keypad', timeout=20000)
        for d in '482916': await pg.keyboard.press(d)
        await pg.wait_for_selector('.grid, .empty', timeout=30000)
        # Gestão > produtos
        await pg.evaluate("location.hash='#/gestao'"); await pg.wait_for_timeout(200)
        print('menu tem produtos:', 'Lista de produtos' in await pg.inner_text('main'))
        await pg.click('text=Lista de produtos'); await pg.wait_for_selector('.srow')
        await pg.screenshot(path=OUT+'01-lista.png', full_page=True)
        await pg.fill('.searchbar input', 'gel'); await pg.wait_for_timeout(100)
        print('busca gel:', await pg.locator('.srow').count())
        await pg.click('.srow'); await pg.wait_for_selector('.prod-head')
        await pg.screenshot(path=OUT+'02-ficha.png', full_page=True)
        await pg.click('text=Comissões de venda'); await pg.wait_for_selector('.pricebox')
        await pg.screenshot(path=OUT+'03-comissoes.png', full_page=True)
        print('comissoes:', (await pg.inner_text('main')).replace('\n',' | ')[:300])
        # editar comissão da Patrícia para 15
        await pg.locator('.prow', has_text='Patrícia').click(); await pg.wait_for_selector('.sheet')
        await pg.fill('.sheet input', '15'); await pg.click('.sheet-f .btn.pri'); await pg.wait_for_timeout(400)
        print('patricia:', await pg.locator('.prow', has_text='Patrícia').inner_text())
        # novo produto
        await pg.evaluate("location.hash='#/produtos'"); await pg.wait_for_selector('.fab')
        await pg.click('.fab'); await pg.wait_for_selector('.sheet')
        si = pg.locator('.sheet input'); await si.nth(0).fill('Sérum facial'); await si.nth(1).fill('Skin care')
        await pg.click('.sheet-f .btn.pri'); await pg.wait_for_selector('.prod-head')
        await pg.locator('details', has_text='Venda').locator('text=Editar').click(); await pg.wait_for_selector('.sheet')
        await pg.check('#vat'); await pg.click('.sheet-f .btn.pri'); await pg.wait_for_selector('.toast'); print('venda sem preço:', await pg.locator('.toast').last.inner_text())
        await pg.fill('.sheet input[inputmode=decimal]', '99,90'); await pg.click('.sheet-f .btn.pri'); await pg.wait_for_timeout(400)
        await pg.click('text=Desativar produto'); await pg.wait_for_timeout(400)
        print('ficha nova:', (await pg.inner_text('.prod-head')).replace('\n',' | '), '| rodapé:', (await pg.inner_text('.meta')).replace('\n',' | '))
        # Venda na comanda
        await pg.evaluate("location.hash='#/novo'"); await pg.fill('.searchbar input', 'Ren'); await pg.click('.clirow')
        await pg.wait_for_selector('.seg'); await pg.click('.seg button:has-text("Produto")'); await pg.wait_for_selector('text=Vendido por')
        opts = await pg.locator('form select').nth(0).locator('option').all_inner_texts(); print('produtos à venda:', opts)
        await pg.locator('form select').nth(0).select_option(label=[o for o in opts if 'Gel' in o][0])
        await pg.fill('input[type=number]', '2')
        vs = await pg.locator('form select').nth(1).locator('option').all_inner_texts()
        await pg.locator('form select').nth(1).select_option(index=[i for i,o in enumerate(vs) if 'Camila' in o][0])
        await pg.locator('input[type=number]').dispatch_event('input')
        await pg.screenshot(path=OUT+'04-vender.png', full_page=True)
        print('resumo:', await pg.inner_text('.totrow'), '|', await pg.inner_text('p.muted.small'))
        await pg.click('form button[type=submit]'); await pg.wait_for_selector('.item.prod')
        # serviço na mesma comanda
        await pg.click('.fab'); await pg.wait_for_selector('form select')
        sels = pg.locator('form.stack select'); o2 = await sels.nth(0).locator('option').all_inner_texts()
        await sels.nth(0).select_option(index=[i for i,o in enumerate(o2) if 'Camila' in o][0]); await pg.locator('input[type=time]').fill('10:00')
        await pg.click('form.stack button[type=submit]'); await pg.wait_for_selector('.item:not(.prod)')
        await pg.screenshot(path=OUT+'05-comanda.png', full_page=True)
        print('comanda:', (await pg.inner_text('main')).replace('\n',' | ')[:400])
        cid = await pg.evaluate("location.hash.split('id=')[1]")
        await pg.evaluate(f"location.hash='#/fechamento?id={cid}'"); await pg.wait_for_selector('.fl')
        await pg.screenshot(path=OUT+'06-fechamento.png', full_page=True)
        await pg.click('.foot .bar'); await pg.wait_for_selector('.payrow'); await pg.click('.payrow.pix .payname'); await pg.click('.foot .bar.pri')
        await pg.wait_for_selector('.sheet'); await pg.fill('.sheet input', '0,00'); await pg.click('.sheet-f .btn.pri')
        await pg.wait_for_selector('.okbar', timeout=5000); print('okbar:', await pg.inner_text('.okbar'))
        lancs = await pg.evaluate("(async()=>{const m=await import('./js/vault.js');return m.all('lanc').map(l=>[l.conta.split(':')[0],l.cat,l.valor,l.desc])})()")
        for l in lancs: print('  lanc', l)
        # agenda: produto não aparece na grade
        await pg.evaluate("location.hash='#/agenda'"); await pg.wait_for_selector('.grid')
        print('blocos na grade:', await pg.locator('.grid .ev, .grid [class*=appt]').all_inner_texts())
        await pg.screenshot(path=OUT+'07-agenda.png')
        await pg.evaluate("location.hash='#/comandas'"); await pg.wait_for_timeout(300); await pg.screenshot(path=OUT+'08-comandas.png')
        await pg.evaluate("location.hash='#/relatorios'"); await pg.wait_for_selector('.kpis'); await pg.screenshot(path=OUT+'09-relatorios.png', full_page=True)
        t = await pg.inner_text('main'); i = t.find('Produtos mais'); print('relatorio:', t[:200].replace('\n',' | '), '...', t[i:i+80].replace('\n',' | '))
        # anulação estorna comissão de venda
        await pg.evaluate(f"location.hash='#/comanda?id={cid}'"); await pg.wait_for_selector('.okbar')
        fid = await pg.evaluate("(async()=>{const m=await import('./js/vault.js');return m.all('fech')[0].id})()")
        await pg.evaluate(f"(async()=>{{const s=await import('./js/services.js');await s.anularFechamento('{fid}')}})()")
        sal = await pg.evaluate("(async()=>{const m=await import('./js/vault.js');const p=m.all('prof').find(x=>x.nome.startsWith('Camila'));return m.all('lanc').filter(l=>l.conta==='prof:'+p.id).reduce((s,l)=>s+l.valor,0)})()")
        print('saldo Camila após anular:', sal)
        # desktop
        await pg.set_viewport_size({'width':1366,'height':860}); await pg.evaluate("location.hash='#/produtos'"); await pg.wait_for_selector('.srow'); await pg.screenshot(path=OUT+'10-desktop.png')
        print('ERRS:', errs)
        await b.close()
asyncio.run(main())
